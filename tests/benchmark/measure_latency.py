"""Measure end-to-end latency: producer send -> Kafka -> streaming Flink job -> PostgreSQL.

A streaming JDBC job (run_jdbc.py without --end) must already be RUNNING. Each trial sends a
small batch under its own run_id, then asks PostgreSQL over one open psql session until
sales_by_store shows every sent row.

  visible_s            : from just before the first send until the rows are visible
  visible_after_ack_s  : the same moment measured from the Kafka acknowledgement of the batch

The result includes the Flink JDBC flush wait (about 1 s or 100 rows) and has a resolution of
one poll round trip. It does not include any dashboard refresh, and it does not apply to
sales_by_store_minute, whose rows appear only after an event-time window closes.

PostgreSQL: local container by default, or PG_HOST/PG_USER/PG_PASSWORD for Azure (as in
sql/postgres/reconcile.py).
"""

from __future__ import annotations

import argparse
import json
import statistics
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from urllib.request import urlopen

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))

from run_stage10 import append_csv, now  # noqa: E402
from producer.kafka_common import Publisher, settings  # noqa: E402
from producer.replay import read_records  # noqa: E402
from sql.postgres.reconcile import psql_argv  # noqa: E402

FIELDS = ["label", "environment", "trial", "run_id", "events", "started_utc", "send_ack_s",
          "visible_s", "visible_after_ack_s", "poll_round_trip_median_ms", "status"]


def streaming_job_running() -> bool:
    with urlopen("http://localhost:8081/jobs/overview", timeout=5) as response:
        jobs = json.load(response)["jobs"]
    return any(job["state"] == "RUNNING" and "pg_sales_by_store" in job["name"] for job in jobs)


class Session:
    """One psql process kept open, so a poll does not pay for a new container or connection."""

    def __init__(self) -> None:
        argv, env = psql_argv([], interactive=True)
        self.process = subprocess.Popen(argv, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                        stderr=subprocess.STDOUT, text=True, env=env, bufsize=1)

    def count(self, run_id: str) -> int:
        # run_id is generated by this script from a validated prefix
        self.process.stdin.write("SELECT 'ROWS=' || COALESCE(SUM(transaction_count), 0) "
                                 f"FROM sales_by_store WHERE run_id = '{run_id}';\n")
        self.process.stdin.flush()
        while True:
            line = self.process.stdout.readline()
            if not line:
                raise RuntimeError("psql session ended")
            if "ERROR" in line:
                raise RuntimeError(f"psql: {line.strip()}")
            text = line.strip()
            if text.startswith("ROWS="):
                return int(text[5:])

    def close(self) -> None:
        self.process.stdin.write("\\q\n")
        self.process.stdin.close()
        self.process.wait(timeout=30)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True, help="JSONL transaction file")
    parser.add_argument("--events", type=int, default=10, help="rows per trial")
    parser.add_argument("--trials", type=int, default=3)
    parser.add_argument("--run-prefix", default="lat", help="letters, digits, underscore; max 30")
    parser.add_argument("--poll-interval", type=float, default=0.1, help="seconds between polls")
    parser.add_argument("--timeout", type=float, default=120.0, help="seconds to wait per trial")
    parser.add_argument("--pause", type=float, default=5.0, help="seconds between trials")
    parser.add_argument("--label", default="dry-run", choices=("dry-run", "official"))
    parser.add_argument("--environment", default="local")
    parser.add_argument("--evidence-dir", type=Path, default=ROOT / "reports/runtime/latency")
    args = parser.parse_args()
    if args.events < 1 or args.trials < 1:
        parser.error("--events and --trials must be positive")
    if not args.run_prefix.replace("_", "").isalnum() or len(args.run_prefix) > 30:
        parser.error("--run-prefix must be letters, digits or underscore, at most 30 characters")
    records = list(read_records(args.input, args.events))
    if len(records) < args.events:
        parser.error("--input has fewer rows than --events")
    if not streaming_job_running():
        raise SystemExit("no RUNNING streaming JDBC job; start run_jdbc.py without --end first")

    bootstrap, topic = settings(None, None)
    suffix = datetime.now(timezone.utc).strftime("%m%d%H%M%S")
    session = Session()
    results = []
    try:
        session.count("warmup")  # pay container start and connection before timing
        for trial in range(1, args.trials + 1):
            run_id = f"{args.run_prefix}_{suffix}_{trial}"
            if session.count(run_id):
                raise RuntimeError(f"{run_id} already has rows")
            publisher = Publisher(bootstrap, topic, run_id)
            publisher.client.list_topics(topic, timeout=10)  # connect before the clock starts
            started_utc, start = now(), time.perf_counter()
            for record in records:
                publisher.send(record)
            stats = publisher.finish()
            acked = time.perf_counter()
            if stats["test_status"] != "PASS":
                raise RuntimeError(f"producer failed: {stats}")
            polls, seen, found = [], None, 0
            while time.perf_counter() - start < args.timeout:
                before = time.perf_counter()
                found = session.count(run_id)
                after = time.perf_counter()
                polls.append((after - before) * 1000)
                if found >= args.events:
                    seen = after
                    break
                time.sleep(args.poll_interval)
            row = {"label": args.label, "environment": args.environment, "trial": trial,
                   "run_id": run_id, "events": args.events, "started_utc": started_utc,
                   "send_ack_s": round(acked - start, 3),
                   "visible_s": round(seen - start, 3) if seen else "",
                   "visible_after_ack_s": round(seen - acked, 3) if seen else "",
                   "poll_round_trip_median_ms": round(statistics.median(polls), 1) if polls else "",
                   "status": "PASS" if seen and found == args.events else "FAIL"}
            append_csv(args.evidence_dir / "latency-end-to-end.csv", FIELDS, row)
            results.append(row)
            print(f"trial {trial}: {row['status']} | {args.events} rows visible after "
                  f"{row['visible_s']} s (after Kafka ack {row['visible_after_ack_s']} s, "
                  f"poll {row['poll_round_trip_median_ms']} ms)", flush=True)
            if trial < args.trials:
                time.sleep(args.pause)
    finally:
        session.close()
    values = [r["visible_s"] for r in results if r["status"] == "PASS"]
    if values:
        print(f"latency over {len(values)} trial(s): min {min(values)} s, "
              f"median {round(statistics.median(values), 3)} s, max {max(values)} s")
    return 0 if len(values) == args.trials else 1


if __name__ == "__main__":
    raise SystemExit(main())
